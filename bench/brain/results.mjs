/**
 * RESULTS.md from runs/ and ablations/, and nothing else.
 *
 * Every run directory holds a metrics.json; this renders each into a table
 * with its commit, reader, k and split beside it. The file is regenerated
 * whole on every call, so a number in RESULTS.md is always the number in a
 * run, and a run that was deleted takes its row with it.
 *
 *   node results.mjs            # writes RESULTS.md and prints it
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'

const here = new URL('.', import.meta.url)
const runs = existsSync(new URL('./runs/', here)) ? readdirSync(new URL('./runs/', here)).filter((d) => existsSync(new URL(`./runs/${d}/metrics.json`, here))).sort() : []
const read = (p) => JSON.parse(readFileSync(new URL(p, here), 'utf8'))
const pct = (x) => (x * 100).toFixed(1)
const cell = (v) => v && typeof v === 'object' && 'mean' in v ? `${pct(v.mean)} [${pct(v.lo)}, ${pct(v.hi)}]` : typeof v === 'number' ? (v <= 1 ? pct(v) : v.toFixed(v < 100 ? 2 : 0)) : String(v ?? '')
const label = { 1: 'multi-hop', 2: 'temporal', 3: 'open-domain', 4: 'single-hop', all: 'all' }

const leaf = (v) => typeof v === 'number' || (v && typeof v === 'object' && 'mean' in v)
/** The first field shaped like {row: {metric: number|interval}} or [{name, metric...}], as a markdown table. */
function gridOf(m) {
  for (const key of ['summary', 'by_size', 'by_style', 'by_category', 'rows', 'table']) {
    const v = m[key]; if (!v || typeof v !== 'object') continue
    const entries = Array.isArray(v) ? v.map((r, i) => [r.name ?? r.row ?? r.style ?? r.size ?? String(i), r]) : Object.entries(v)
    if (!entries.length || !entries.every(([, r]) => r && typeof r === 'object' && Object.values(r).some(leaf))) continue
    const cols = [...new Set(entries.flatMap(([, r]) => Object.keys(r).filter((k) => leaf(r[k]) && !['name', 'row', 'style', 'size'].includes(k))))]
    let out = `| ${key === 'summary' ? 'category' : key.replace('by_', '')} | ${cols.join(' | ')} |\n|---|${cols.map(() => '---').join('|')}|\n`
    for (const [name, r] of entries) out += `| ${label[name] ?? name} | ${cols.map((k) => cell(r[k])).join(' | ')} |\n`
    return out
  }
  return null
}

let md = `# Results\n\nGenerated by \`node results.mjs\` from \`runs/*/metrics.json\`. Do not edit; rerun.\nEvery interval is a bootstrap 95% CI over questions (1000 resamples). Splits and readers are those declared in METHOD.md.\n\n`
const groups = {}
for (const d of runs) (groups[d.split('-')[0]] ??= []).push(d)

for (const [bench, dirs] of Object.entries(groups)) {
  md += `## ${bench}\n\n`
  for (const d of dirs) {
    const m = read(`./runs/${d}/metrics.json`), meta = existsSync(new URL(`./runs/${d}/meta.json`, here)) ? read(`./runs/${d}/meta.json`) : {}
    md += `### ${d}\n\n`
    const facts = [['split', m.split ?? meta.split], ['k', m.k ?? meta.k], ['reader', m.reader ?? meta.reader], ['facts', m.facts ?? meta.facts], ['embedding', meta.embedding], ['commit', meta.commit], ['prompt sha', meta.prompt_sha ?? meta.prompt]].filter(([, v]) => v != null)
    if (facts.length) md += facts.map(([k, v]) => `${k}: \`${v}\``).join(' · ') + '\n\n'
    const grid = gridOf(m)
    if (grid) md += grid + '\n'
    else if (typeof m.table === 'string') md += m.table + '\n\n'
    else md += '```json\n' + JSON.stringify(m, null, 1).slice(0, 4000) + '\n```\n\n'
  }
}
const abl = existsSync(new URL('./ablations/', here)) ? readdirSync(new URL('./ablations/', here)).filter((f) => f.endsWith('.json')).sort() : []
if (abl.length) {
  md += `## ablations (dev split only)\n\n`
  for (const f of abl) { const a = read(`./ablations/${f}`)
    if (f.startsWith('frozen')) md += `**${f}** — frozen configuration: row \`${a.row}\`, facts \`${a.facts}\`, k ${a.k}, commit \`${a.commit}\`, objective ${pct(a.objective)} after ${a.evaluations} evaluations.\n\nweights \`${JSON.stringify(a.w)}\` · budgets \`${JSON.stringify(a.budget)}\`\n\n`
    else if (a.evaluations) { md += `**${f}** — ${a.evaluations.length} evaluations, objective: ${a.objective}. Best ten:\n\n| objective | weights | budgets |\n|---|---|---|\n`; for (const e of [...a.evaluations].sort((x, y) => y.objective - x.objective).slice(0, 10)) md += `| ${pct(e.objective)} | \`${JSON.stringify(e.w)}\` | \`${JSON.stringify(e.budget)}\` |\n`; md += '\n' }
    else md += `**${f}**\n\n\`\`\`json\n${JSON.stringify(a, null, 1).slice(0, 3000)}\n\`\`\`\n\n` }
}
writeFileSync(new URL('./RESULTS.md', here), md)

// The same numbers as data, for hanzo.ai/benchmarks: one section per run.
const sections = runs.map((d) => { const m = read(`./runs/${d}/metrics.json`), meta = existsSync(new URL(`./runs/${d}/meta.json`, here)) ? read(`./runs/${d}/meta.json`) : {}
  const key = ['summary', 'by_size', 'by_style', 'by_category', 'rows', 'table'].find((k) => m[k] && typeof m[k] === 'object')
  const v = key ? m[key] : null
  const entries = !v ? [] : Array.isArray(v) ? v.map((r, i) => [r.name ?? r.row ?? r.style ?? r.size ?? String(i), r]) : Object.entries(v)
  const categories = entries.filter(([, r]) => r && typeof r === 'object' && Object.values(r).some(leaf)).map(([c, s]) => ({ name: label[c] ?? c, n: s.n ?? null,
    metrics: Object.fromEntries(Object.entries(s).filter(([k, x]) => k !== 'n' && leaf(x)).map(([k, x]) => [k, x && typeof x === 'object' ? { mean: x.mean, lo: x.lo, hi: x.hi } : x])) }))
  return { bench: d.split('-')[0], run: d, row: m.row ?? null, split: m.split ?? meta.split ?? null, k: m.k ?? meta.k ?? null, reader: m.reader ?? meta.reader ?? null, facts: m.facts ?? meta.facts ?? null, commit: meta.commit ?? meta.commit ?? null,
    categories, table: typeof m.table === 'string' ? m.table : null } })
writeFileSync(new URL('./benchmarks.json', here), JSON.stringify({ generated: new Date().toISOString(), sections }, null, 1))
console.log(md)

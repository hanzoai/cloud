package fleet

import (
	_ "embed"
	"encoding/json"
)

// WHAT A SUBSYSTEM SERVES IS KNOWN BEFORE IT RUNS.
//
// Discovery used to ask every subsystem, and asking a lazy one starts it. One
// tools/list therefore started the whole catalog — a hundred processes for a
// question about names — and nothing ever brought that back down, so the host's
// resident cost tracked the number of subsystems that EXIST rather than the
// number in use. Measured on the deployed host: 19 processes at boot, 124 at the
// kill, ~106MiB each under one cap.
//
// The catalog is those same answers, read from what each subsystem published at
// build time. A subsystem that is already running is still ASKED — it is up, so
// asking costs nothing and its answer is the live one, which is what a plane
// whose tools are rows needs. A subsystem that is not running is answered from
// here, and stays down until someone calls it.
//
// It cannot drift the way a hand-kept catalogue did: it is generated from
// plugin/<app>/openapi.json, each written by that app's own binary from its own
// router, regenerated by `make -f mk/fleet.mk check` and held against the woven
// document by the weave. See plugin/gen-fleet-catalog.
//
//go:embed catalog.json
var catalogJSON []byte

// Op is one operation as its subsystem published it: the id its own registry
// answers to, and what it wrote about it.
//
// There is no schema here on purpose. The door publishes one tool per subsystem
// whose enum carries NAMES, and a model fetches the schema for the one it picked
// — a fetch that reaches one subsystem instead of all of them, which is the
// whole shape this exists to keep.
type Op struct {
	ID  string `json:"id"`
	Doc string `json:"doc"`
	// Read says the operation is a GET. A subsystem whose every offered
	// operation reads is published with readOnlyHint, which is the one MCP
	// annotation a client acts on — and the only honest place to set it, since a
	// tool carries a whole subsystem and the hint is per tool.
	Read bool `json:"read,omitempty"`
}

var catalog = loadCatalog()

func loadCatalog() map[string][]Op {
	out := map[string][]Op{}
	// A malformed catalog degrades to asking, which is the behaviour that
	// preceded it — never to a fleet that publishes nothing.
	_ = json.Unmarshal(catalogJSON, &out)
	return out
}

// Published is what app declared at build time, or nil if the catalog does not
// carry it — a subsystem added since the last generate, which is asked.
func Published(app string) []Op { return catalog[app] }

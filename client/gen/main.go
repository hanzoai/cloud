// Command gen emits one typed client package per app that declares plane ops.
//
//	go run ./client/gen
//
// # Why this is a projection and not 45 hand-written clients
//
// An app already declares everything a caller needs to reach it:
//
//	zip.Post[client.BalanceIn, client.Balance](cloud.Plane(), "/finance/balance",
//	    planeBalance, zip.WithOperationID(client.FinanceBalance))
//
// That one expression names the app (its directory), the op, the request type
// and the response type. Cloud already turns the same registry into an OpenAPI
// document, a CLI, an MCP tool list and a routing declaration. A typed Go client
// for a peer call is ONE MORE PROJECTION of that document — which is exactly why
// it belongs here rather than being written out by hand once per caller.
//
// What it buys is a compiler check that no amount of care buys today. A hand-
// written peer call is five independent facts that must agree at RUN time:
//
//	cloud.Ask[client.BalanceIn, client.Balance](ctx, "commerce", client.FinanceBalance, in)
//	          ^ In            ^ Out            ^ app        ^ op
//
// Nothing stops a caller pairing commerce's op with iam's app name, or
// BalanceIn with Txns. The generated wrapper fixes all four to each other at the
// point of declaration, so the mismatch stops compiling:
//
//	commerce.FinanceBalance(ctx, &client.BalanceIn{...})
//
// # It reads the SOURCE, and a test checks it against the LIVE registry
//
// zip's own [zip.Declaration] argues a declaration must come from the live
// router, never the AST, because an AST cannot cross a repository boundary. That
// argument is about a HOST discovering a plugin it does not build. This
// generator emits Go source into the same module as the declaration it reads, so
// the boundary does not exist here — and reading source buys hermeticity the
// runtime path cannot: no store is opened, no boot order matters, no app has to
// mount before it can be described. zipdoc, the repo's other Go emitter, reads
// these same call sites the same way.
//
// The doctrine is still honoured, by a gate rather than by the mechanism:
// client/client_registry_test.go MOUNTS an app and asserts the ops this generator
// found are exactly the ops the live plane registry holds. Source is the input;
// the running registry is the judge.
package main

import (
	"fmt"
	"github.com/hanzoai/cloud/manifest"
	"go/ast"
	"go/format"
	"go/types"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

// header marks every emitted file. Same sentence as zipdoc's, because a reader
// who has seen one generated file in this repo has seen them all.
const header = "// Code generated by client/gen; DO NOT EDIT."

// planeCall is the receiver that makes an op INTERNAL. An op registered on the
// app's own router is a public address and gets a REST client from the OpenAPI
// document; only ops on cloud.Plane() ride the peer plane.
const planeCall = "Plane"

// op is one declared plane op, reduced to what a caller has to know.
type op struct {
	Name    string // the operationId CONSTANT's identifier, e.g. "FinanceBalance"
	Ref     string // how to spell it in generated source, e.g. "client.FinanceBalance"
	In, Out string // rendered type expressions, e.g. "client.BalanceIn"
	Summary string
}

// client is one app's whole peer surface.
type client struct {
	App     string // the app name, which is also its socket name
	Ops     []op
	Imports map[string]string // path -> local name
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "client/gen:", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := repoRoot()
	if err != nil {
		return err
	}
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax |
			packages.NeedTypes | packages.NeedTypesInfo | packages.NeedDeps | packages.NeedImports,
		Dir: root,
		// The FTS5 tag the image ships. A package that does not build under the
		// shipped tags is a package this must not silently describe as empty.
		BuildFlags: []string{"-tags", "sqlite_fts5"},
	}
	pkgs, err := packages.Load(cfg, "./apps/...")
	if err != nil {
		return err
	}
	byApp := map[string]*client{}
	for _, p := range pkgs {
		if len(p.Errors) > 0 {
			// A package that does not type-check cannot be read for types. Refusing
			// is the point: emitting an empty client for it would publish "this app
			// has no peer surface" about an app whose surface simply failed to load.
			return fmt.Errorf("%s: %v", p.PkgPath, p.Errors[0])
		}
		app := appOf(p, root)
		if app == "" {
			continue
		}
		for _, f := range p.Syntax {
			collect(p, f, app, byApp)
		}
	}
	names := make([]string, 0, len(byApp))
	for n := range byApp {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		c := byApp[n]
		sort.Slice(c.Ops, func(i, j int) bool { return c.Ops[i].Name < c.Ops[j].Name })
		src, err := c.render()
		if err != nil {
			return err
		}
		dir := filepath.Join(root, "client", n)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
		if err := writeIfChanged(filepath.Join(dir, n+".go"), src); err != nil {
			return err
		}
	}
	// The second projection: the ZAP codec for every plane type that has declared
	// its wire. It is the same job — project the one declaration — so it is the
	// same command, and there is nothing to remember to run separately.
	wired, err := codecs(root)
	if err != nil {
		return err
	}

	fmt.Printf("client/gen: %d peers\n", len(names))
	for _, n := range names {
		fmt.Printf("  %-12s %d ops\n", n, len(byApp[n].Ops))
	}
	fmt.Printf("client/gen: %d types carry their own wire\n", len(wired))
	for _, n := range wired {
		fmt.Printf("  %s\n", n)
	}
	return nil
}

// appOf returns the app name a package belongs to — the directory under apps/,
// which is also the name its socket is bound under. A nested package (apps/x/y)
// belongs to no app: it declares no plane ops of its own and its parent's name
// would be a guess.
func appOf(p *packages.Package, root string) string {
	if len(p.GoFiles) == 0 {
		return ""
	}
	rel, err := filepath.Rel(filepath.Join(root, "apps"), filepath.Dir(p.GoFiles[0]))
	if err != nil || strings.Contains(rel, string(filepath.Separator)) || rel == "." || rel == ".." {
		return ""
	}
	// The DIRECTORY is not the name. A capability's address and its package are
	// separate facts (manifest.App.Pkg), so the name comes from the manifest —
	// the file that owns it — and a directory no app claims yields none.
	return manifest.NameFor(rel)
}

// collect walks one file for typed registrations on cloud.Plane().
func collect(p *packages.Package, f *ast.File, app string, byApp map[string]*client) {
	ast.Inspect(f, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok || len(call.Args) < 3 {
			return true
		}
		in, out, ok := typeArgs(p, call.Fun)
		if !ok || !isPlane(p, call.Args[0]) {
			return true
		}
		name, ref, ok := opID(p, call.Args[3:])
		if !ok {
			// An op with no declared id answers under a derived name that the
			// generator has no stable way to spell. Skipping it silently would
			// publish an incomplete client, so say so and let the declaration be
			// fixed.
			fmt.Fprintf(os.Stderr, "client/gen: %s: a plane op with no WithOperationID is unreachable by name — skipped\n", p.Fset.Position(call.Pos()))
			return true
		}
		c := byApp[app]
		if c == nil {
			c = &client{App: app, Imports: map[string]string{}}
			byApp[app] = c
		}
		c.Ops = append(c.Ops, op{
			Name:    name,
			Ref:     c.qualify(ref),
			In:      c.spell(in),
			Out:     c.spell(out),
			Summary: summary(p, call.Args[3:]),
		})
		return true
	})
}

// typeArgs pulls In and Out off a generic registration.
//
// It reads types.Info.Instances rather than the AST's index expression, because
// the two spellings of the same registration are not distinguishable in source:
//
//	zip.Post[client.ReserveIn, client.Reserved](cloud.Plane(), ...)   // explicit
//	zip.Post(cloud.Plane(), "/treasury/reserve", planeReserve, ...) // inferred
//
// Both instantiate the same generic function, and the type checker records the
// arguments for both. Reading the index expression instead found only the first
// form and silently dropped treasury's only op — an app with a peer surface
// reported as having none, which is the exact failure mode this generator exists
// to remove.
func typeArgs(p *packages.Package, fun ast.Expr) (in, out types.Type, ok bool) {
	sel, isSel := fun.(*ast.SelectorExpr)
	if !isSel {
		// The explicit form wraps the selector in an index expression.
		idx, isIdx := fun.(*ast.IndexListExpr)
		if !isIdx {
			return nil, nil, false
		}
		sel, isSel = idx.X.(*ast.SelectorExpr)
		if !isSel {
			return nil, nil, false
		}
	}
	if !isZip(p, sel) {
		return nil, nil, false
	}
	inst, found := p.TypesInfo.Instances[sel.Sel]
	if !found || inst.TypeArgs == nil || inst.TypeArgs.Len() != 2 {
		return nil, nil, false
	}
	return inst.TypeArgs.At(0), inst.TypeArgs.At(1), true
}

// isZip reports whether sel names one of zip's typed registrars.
func isZip(p *packages.Package, sel *ast.SelectorExpr) bool {
	switch sel.Sel.Name {
	case "Post", "Get", "Put", "Patch", "Delete":
	default:
		return false
	}
	id, ok := sel.X.(*ast.Ident)
	if !ok {
		return false
	}
	pn, ok := p.TypesInfo.Uses[id].(*types.PkgName)
	return ok && pn.Imported().Path() == "github.com/zap-proto/zip"
}

// isPlane reports whether the registration target is cloud.Plane() — the one
// receiver that makes an op internal.
func isPlane(p *packages.Package, e ast.Expr) bool {
	switch v := e.(type) {
	case *ast.CallExpr:
		sel, ok := v.Fun.(*ast.SelectorExpr)
		if !ok || sel.Sel.Name != planeCall {
			return false
		}
		id, ok := sel.X.(*ast.Ident)
		if !ok {
			return false
		}
		pn, ok := p.TypesInfo.Uses[id].(*types.PkgName)
		return ok && pn.Imported().Path() == "github.com/hanzoai/cloud"
	case *ast.Ident:
		// `p := cloud.Plane()` then `zip.Post[...](p, ...)` — meter_rpc.go does
		// exactly this, and reading only the direct call would miss both its ops.
		obj, ok := p.TypesInfo.Uses[v].(*types.Var)
		if !ok {
			return false
		}
		for id, def := range p.TypesInfo.Defs {
			if def != obj {
				continue
			}
			if a, ok := assignedFrom(p, id); ok {
				return isPlane(p, a)
			}
		}
	}
	return false
}

// assignedFrom finds the right-hand side a local was defined from.
func assignedFrom(p *packages.Package, id *ast.Ident) (ast.Expr, bool) {
	for _, f := range p.Syntax {
		var found ast.Expr
		ast.Inspect(f, func(n ast.Node) bool {
			as, ok := n.(*ast.AssignStmt)
			if !ok || len(as.Lhs) != 1 || len(as.Rhs) != 1 {
				return true
			}
			if lid, ok := as.Lhs[0].(*ast.Ident); ok && lid == id {
				found = as.Rhs[0]
			}
			return true
		})
		if found != nil {
			return found, true
		}
	}
	return nil, false
}

// opID reads the operationId out of the registration's options. It wants the
// CONSTANT, not the string: emitting client.FinanceBalance rather than
// "finance_balance" means a rename moves both halves at once, which is the whole
// reason the constants exist.
func opID(p *packages.Package, opts []ast.Expr) (name, ref string, ok bool) {
	for _, o := range opts {
		call, isCall := o.(*ast.CallExpr)
		if !isCall || len(call.Args) != 1 {
			continue
		}
		sel, isSel := call.Fun.(*ast.SelectorExpr)
		if !isSel || sel.Sel.Name != "WithOperationID" {
			continue
		}
		id, isSel2 := call.Args[0].(*ast.SelectorExpr)
		if !isSel2 {
			continue
		}
		pn, isPkg := p.TypesInfo.Uses[id.X.(*ast.Ident)].(*types.PkgName)
		if !isPkg {
			continue
		}
		return id.Sel.Name, pn.Imported().Path() + "." + id.Sel.Name, true
	}
	return "", "", false
}

// summary lifts WithSummary's literal, so the generated call carries the same
// sentence the document does.
func summary(p *packages.Package, opts []ast.Expr) string {
	for _, o := range opts {
		call, ok := o.(*ast.CallExpr)
		if !ok || len(call.Args) != 1 {
			continue
		}
		sel, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || sel.Sel.Name != "WithSummary" {
			continue
		}
		if tv, ok := p.TypesInfo.Types[call.Args[0]]; ok && tv.Value != nil {
			return strings.Trim(tv.Value.String(), `"`)
		}
	}
	return ""
}

// qualify records the import a reference needs and returns how to spell it.
func (c *client) qualify(ref string) string {
	i := strings.LastIndex(ref, ".")
	path, name := ref[:i], ref[i+1:]
	return c.use(path) + "." + name
}

// use records an import and returns its local name.
func (c *client) use(path string) string {
	if n, ok := c.Imports[path]; ok {
		return n
	}
	n := path[strings.LastIndex(path, "/")+1:]
	c.Imports[path] = n
	return n
}

// spell writes a type as generated source, recording whatever imports it needs.
func (c *client) spell(t types.Type) string {
	return types.TypeString(t, func(p *types.Package) string { return c.use(p.Path()) })
}

func (c *client) render() ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "%s\n\n", header)
	fmt.Fprintf(&b, `// Package %s is the typed client for the %q app's internal ops.
//
// Every call here is a ZAP call BY NAME over the peer's unix socket — no URL, no
// env var, no HTTP round trip, and no way to reach the public edge by accident.
// That last one is not a style preference: %s's own callers used to reach it
// through CLOUD_COMMERCE_HTTP_URL, which defaulted to the api.hanzo.ai edge —
// the SAME binary — so the forwarder re-entered itself and the billing gate died
// of it. A call by name cannot express that mistake.
//
// It depends on the CONTRACT (package client) and never on %s's implementation,
// so importing it costs a caller nothing but the types it is already sending.
package %s

`, c.App, c.App, c.App, c.App, c.App)

	paths := make([]string, 0, len(c.Imports))
	for p := range c.Imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	b.WriteString("import (\n\t\"context\"\n\n")
	for _, p := range paths {
		fmt.Fprintf(&b, "\t%q\n", p)
	}
	b.WriteString(")\n\n")

	fmt.Fprintf(&b, `// App is the peer's name, which is also the socket it answers on. It is the
// ONE place this package spells it.
const App = %q

`, c.App)

	b.WriteString(`// Ops is every op this peer answers, in the spelling the wire uses.
//
// It exists so a test can hold this generated surface against the LIVE plane
// registry and fail when they disagree — which is what lets this be generated
// from source without the document drifting away from the program. See
// plane_registry_test.go.
var Ops = []string{
`)
	for _, o := range c.Ops {
		fmt.Fprintf(&b, "\t%s,\n", o.Ref)
	}
	b.WriteString("}\n\n")

	for _, o := range c.Ops {
		if o.Summary != "" {
			fmt.Fprintf(&b, "// %s %s.\n//\n", o.Name, lower(o.Summary))
		}
		fmt.Fprintf(&b, "// Calls %s on %s over the peer plane.\n", o.Ref, c.App)
		ask := c.use("github.com/hanzoai/cloud/client")
		if o.In == "struct{}" {
			// An op whose input declares no fields takes no argument. The empty
			// struct is not information a caller has to supply — it is the absence
			// of information, and making it a parameter only invites &struct{}{} at
			// every call site. The org such an op acts for rides the caller, so
			// there is genuinely nothing left to pass.
			fmt.Fprintf(&b, "func %s(ctx context.Context) (*%s, error) {\n", o.Name, o.Out)
			fmt.Fprintf(&b, "\treturn %s.Call[struct{}, %s](ctx, App, %s, &struct{}{})\n}\n\n",
				ask, o.Out, o.Ref)
			continue
		}
		fmt.Fprintf(&b, "func %s(ctx context.Context, in *%s) (*%s, error) {\n", o.Name, o.In, o.Out)
		fmt.Fprintf(&b, "\treturn %s.Call[%s, %s](ctx, App, %s, in)\n}\n\n",
			ask, o.In, o.Out, o.Ref)
	}
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("generated source for %s does not parse: %w\n%s", c.App, err, b.String())
	}
	return src, nil
}

// lower drops the leading capital off a summary so it reads as a clause.
func lower(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

// writeIfChanged leaves the file alone when the bytes match, so a regenerate
// that changes nothing shows up as no diff and the drift gate stays meaningful.
func writeIfChanged(path string, src []byte) error {
	if old, err := os.ReadFile(path); err == nil && string(old) == string(src) {
		return nil
	}
	return os.WriteFile(path, src, 0o644)
}

// repoRoot walks up to the directory holding go.mod.
func repoRoot() (string, error) {
	d, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(d, "go.mod")); err == nil {
			return d, nil
		}
		p := filepath.Dir(d)
		if p == d {
			return "", fmt.Errorf("no go.mod above %s", d)
		}
		d = p
	}
}

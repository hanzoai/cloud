package main

// codec.go emits client/zap_gen.go: the ZAP codec for every plane type that has
// DECLARED its wire with `zap:` tags.
//
// # Why generated and not derived
//
// The op-call plane carries In and Out as ZAP, and zip derives the layout from
// the Go type by reflection. The derivation is cached; the COPY is not, so every
// call runs reflect.ValueOf, sizes a builder by guess and walks the fields again
// — work whose answer was fixed when the type was declared. Measured on a
// hundred-row page, that costs 103 allocations against 2 and 10µs against 156ns,
// and it scales with the rows because a reflective decode MATERIALISES every one
// whether the caller reads it or not.
//
// It is also the only way to carry an id. A fixed-size array is refused outright
// by the reflective encoder — `zapenc: array cannot cross the plane` — so
// bytes_fixed[32] cannot cross today at all.
//
// # The wire does not move
//
// This emits the SAME BYTES the reflective encoder writes, field for field and
// in the same order, because a rolling deploy has one pod on each path and they
// must read one message the same way. [client.TestTheGeneratedCodecKeepsTheWire]
// holds that against recorded bytes.
//
// The sequence it reproduces: every list is written FIRST (SetList takes an
// offset that must already exist), then the object is started at the declared
// size, then each field is set in declaration order, then the list slots are
// filled. Deferred text and bytes are laid down by the builder in the order they
// were set, so declaration order is load-bearing and not cosmetic.
//
// # One declaration
//
// The offsets are [layout.Of]'s, checked against the `zap:` tag on every field.
// The same function answers for the .zap schema, so the tag a reviewer reads, the
// ordinal the schema states and the constant this file emits are one fact.

import (
	"bytes"
	"fmt"
	"go/format"
	"go/types"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"golang.org/x/tools/go/packages"

	"github.com/hanzoai/cloud/client/layout"
)

// codecs emits the codec for package plane. It returns the type names it wrote.
func codecs(root string) ([]string, error) {
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax |
			packages.NeedTypes | packages.NeedTypesInfo,
		Dir: root,
	}
	pkgs, err := packages.Load(cfg, "./client")
	if err != nil {
		return nil, err
	}
	if len(pkgs) != 1 {
		return nil, fmt.Errorf("plane: loaded %d packages, want 1", len(pkgs))
	}
	p := pkgs[0]
	if len(p.Errors) > 0 {
		return nil, fmt.Errorf("%s: %v", p.PkgPath, p.Errors[0])
	}

	// Two passes. The first finds every type that has declared its wire, because
	// a nested field's codec must exist before the field that reaches it can be
	// emitted, and declaration order in the file says nothing about that.
	declared := map[string]layout.Layout{}
	scope := p.Types.Scope()
	for _, n := range scope.Names() {
		tn, ok := scope.Lookup(n).(*types.TypeName)
		if !ok {
			continue
		}
		s, ok := tn.Type().Underlying().(*types.Struct)
		if !ok {
			continue
		}
		lay, err := layout.Of(s)
		if err != nil {
			// A type nobody tagged is not this generator's business; a type
			// SOMEBODY tagged that does not lay out is a defect and says so.
			if taggedAnywhere(s) {
				return nil, fmt.Errorf("%s: %w", n, err)
			}
			continue
		}
		if lay.Tagged() {
			declared[n] = lay
		}
	}

	names := make([]string, 0, len(declared))
	for n := range declared {
		names = append(names, n)
	}
	sort.Strings(names)

	var body bytes.Buffer
	for _, n := range names {
		if err := emit(&body, n, declared[n], declared); err != nil {
			return nil, fmt.Errorf("%s: %w", n, err)
		}
	}
	if len(names) == 0 {
		return nil, nil
	}

	// The import block is derived from what was actually emitted rather than
	// declared up front: a codec for a package with no lists needs neither
	// binary nor the width helper, and an unused import does not compile.
	var out bytes.Buffer
	fmt.Fprint(&out, "// Code generated by client/gen; DO NOT EDIT.\n\npackage client\n\nimport (\n")
	uses := func(tok string) bool { return bytes.Contains(body.Bytes(), []byte(tok)) }
	if uses("binary.") || uses("planeWide(") {
		fmt.Fprint(&out, "\t\"encoding/binary\"\n")
	}
	fmt.Fprint(&out, "\t\"fmt\"\n")
	if uses("math.") {
		fmt.Fprint(&out, "\t\"math\"\n")
	}
	if uses("strings.") {
		fmt.Fprint(&out, "\t\"strings\"\n")
	}
	fmt.Fprint(&out, "\n\tzap \"github.com/zap-proto/go\"\n\t\"github.com/zap-proto/zip\"\n)\n\n")
	if uses("planeWide(") {
		fmt.Fprint(&out, wideHelper)
	}
	out.Write(body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("emitted source does not parse: %w\n%s", err, out.String())
	}
	if err := writeIfChanged(filepath.Join(root, "client", "zap_gen.go"), src); err != nil {
		return nil, err
	}
	return names, nil
}

// taggedAnywhere reports whether a struct carries a zap tag on any field, which
// is how a half-declared type is told from an undeclared one.
func taggedAnywhere(s *types.Struct) bool {
	for i := range s.NumFields() {
		if strings.Contains(s.Tag(i), `zap:"`) {
			return true
		}
	}
	return false
}

// wideHelper reads a list element's little-endian bytes into a uint64. A list
// element is written at its own width, so a shorter one is zero-extended here and
// sign-extended by the caller — the rule the reflective decoder already follows.
const wideHelper = `// planeWide reads a list element's little-endian bytes, whatever its width.
func planeWide(b []byte) uint64 {
	var wide [8]byte
	copy(wide[:], b)
	return binary.LittleEndian.Uint64(wide[:])
}

`

func emit(w *bytes.Buffer, name string, lay layout.Layout, declared map[string]layout.Layout) error {
	// Refuse before writing a line: a half-emitted codec whose remaining fields
	// fell through would encode a value nobody sent.
	for _, f := range lay.Fields {
		if err := supported(f, declared); err != nil {
			return err
		}
	}

	lo := lower(name)
	fmt.Fprintf(w, "// ---- %s %s\n\n", name, strings.Repeat("-", max(1, 66-len(name))))
	fmt.Fprintf(w, "const (\n")
	for _, f := range lay.Fields {
		fmt.Fprintf(w, "\t%s%sOff = %d\n", lo, f.Name, f.Offset)
	}
	fmt.Fprintf(w, "\t%sSize = %d\n)\n\n", lo, lay.Size)

	fmt.Fprintf(w, "var _ zip.Wire = (*%s)(nil)\n\n", name)

	// ---- Marshal
	fmt.Fprintf(w, "// MarshalZAP writes %s from constant offsets. No layout is derived\n"+
		"// and nothing is reflected over.\n", name)
	fmt.Fprintf(w, "func (x *%s) MarshalZAP() ([]byte, error) {\n", name)
	// A nil input is an absent body, not an empty object — the same answer the
	// reflective encoder gives. A handler that returns a nil *Out reaches here as
	// a non-nil interface holding one, so without this the generated path panics
	// exactly where the reflective path answered.
	fmt.Fprintf(w, "\tif x == nil {\n\t\treturn nil, nil\n\t}\n")
	fmt.Fprintf(w, "\tb := zap.NewBuilder(zap.HeaderSize + %sSize + %s)\n", lo, capacity(lo, lay))

	// Lists are written before the object, because SetList takes an offset that
	// must already exist. Same order the reflective encoder uses.
	for _, f := range lay.Fields {
		if f.Kind != layout.List {
			continue
		}
		if err := emitListWrite(w, lo, f); err != nil {
			return err
		}
	}
	fmt.Fprintf(w, "\tob := b.StartObject(%sSize)\n", lo)
	for _, f := range lay.Fields {
		if f.Kind == layout.List {
			continue
		}
		emitSet(w, lo, f)
	}
	for _, f := range lay.Fields {
		if f.Kind != layout.List {
			continue
		}
		fmt.Fprintf(w, "\tif %sN > 0 {\n\t\tob.SetList(%s%sOff, %sOff, %sN)\n\t}\n",
			lower(f.Name), lo, f.Name, lower(f.Name), lower(f.Name))
	}
	fmt.Fprintf(w, "\tob.FinishAsRoot()\n\treturn b.Finish(), nil\n}\n\n")

	// ---- Unmarshal
	fmt.Fprintf(w, "// UnmarshalZAP reads %s out of the buffer that arrived.\n", name)
	fmt.Fprintf(w, "func (x *%s) UnmarshalZAP(data []byte) error {\n", name)
	// An empty message leaves the value untouched: a void reply is an absence,
	// not a zero somebody might mistake for an answer.
	fmt.Fprintf(w, "\tif x == nil || len(data) == 0 {\n\t\treturn nil\n\t}\n")
	fmt.Fprintf(w, "\tm, err := zap.Parse(data)\n\tif err != nil {\n\t\treturn fmt.Errorf(%q, err)\n\t}\n",
		"plane: "+name+": %w")
	fmt.Fprintf(w, "\to := m.Root()\n")
	for _, f := range lay.Fields {
		if err := emitGet(w, lo, f); err != nil {
			return err
		}
	}
	fmt.Fprintf(w, "\treturn nil\n}\n\n")
	return nil
}

// capacity is the builder size that holds the whole message without growing:
// the fixed area plus every variable value, plus alignment slack per slot.
func capacity(lo string, lay layout.Layout) string {
	var terms []string
	slack := 8
	for _, f := range lay.Fields {
		switch f.Kind {
		case layout.Text, layout.Bytes:
			terms = append(terms, "len(x."+f.Name+")")
			slack += 8
		case layout.Struct, layout.List:
			// A nested value's size is not known without building it; the builder
			// grows, which costs an allocation and never a wrong byte.
			slack += 64
		}
	}
	terms = append(terms, strconv.Itoa(slack))
	return strings.Join(terms, "+")
}

func supported(f layout.Field, declared map[string]layout.Layout) error {
	switch f.Kind {
	case layout.Struct:
		n, ok := named(f.Type)
		if !ok || !isDeclared(n, declared) {
			return fmt.Errorf("field %s: a nested %s has no declared wire; tag its fields too",
				f.Name, f.Type)
		}
	case layout.List:
		if f.Elem == nil {
			return fmt.Errorf("field %s: a list with no element type", f.Name)
		}
		if f.Elem.Kind == layout.Struct {
			n, ok := named(f.Elem.Type)
			if !ok || !isDeclared(n, declared) {
				return fmt.Errorf("field %s: a list of %s has no declared element wire; tag its fields too",
					f.Name, f.Elem.Type)
			}
		}
		if f.Elem.Ptr {
			return fmt.Errorf("field %s: a list of pointers is not emitted; use a list of values", f.Name)
		}
	case layout.Fixed:
		if f.Ptr {
			return fmt.Errorf("field %s: a pointer to bytes_fixed is not emitted", f.Name)
		}
	}
	return nil
}

func named(t types.Type) (string, bool) {
	n, ok := t.(*types.Named)
	if !ok {
		return "", false
	}
	return n.Obj().Name(), true
}

func isDeclared(n string, declared map[string]layout.Layout) bool {
	_, ok := declared[n]
	return ok
}

// setter is the builder call for one kind, and getter its reader. They are one
// table so the two directions cannot name different offsets or widths.
var setter = map[layout.Kind]string{
	layout.Bool: "SetBool", layout.Int8: "SetInt8", layout.Int16: "SetInt16",
	layout.Int32: "SetInt32", layout.Int64: "SetInt64",
	layout.Uint8: "SetUint8", layout.Uint16: "SetUint16",
	layout.Uint32: "SetUint32", layout.Uint64: "SetUint64",
	layout.Float32: "SetFloat32", layout.Float64: "SetFloat64",
	layout.Text: "SetText", layout.Bytes: "SetBytes",
}

var getter = map[layout.Kind]string{
	layout.Bool: "Bool", layout.Int8: "Int8", layout.Int16: "Int16",
	layout.Int32: "Int32", layout.Int64: "Int64",
	layout.Uint8: "Uint8", layout.Uint16: "Uint16",
	layout.Uint32: "Uint32", layout.Uint64: "Uint64",
	layout.Float32: "Float32", layout.Float64: "Float64",
	layout.Text: "Text", layout.Bytes: "Bytes",
}

// goKind is the Go type each kind is read back as, for the conversion a defined
// type (type Cents int64) needs on the way in and out.
var goKind = map[layout.Kind]string{
	layout.Bool: "bool", layout.Int8: "int8", layout.Int16: "int16",
	layout.Int32: "int32", layout.Int64: "int64",
	layout.Uint8: "uint8", layout.Uint16: "uint16",
	layout.Uint32: "uint32", layout.Uint64: "uint64",
	layout.Float32: "float32", layout.Float64: "float64",
	layout.Text: "string", layout.Bytes: "[]byte",
}

func emitSet(w *bytes.Buffer, lo string, f layout.Field) {
	off := lo + f.Name + "Off"
	ref := "x." + f.Name
	indent := "\t"
	if f.Ptr {
		// An absent pointer writes nothing: a null, not a zero. Same rule the
		// reflective encoder follows, and the field's slot is already zeroed.
		fmt.Fprintf(w, "\tif x.%s != nil {\n", f.Name)
		ref = "*x." + f.Name
		indent = "\t\t"
	}
	switch f.Kind {
	case layout.Fixed:
		fmt.Fprintf(w, "%sob.SetBytesFixed(%s, %s[:])\n", indent, off, ref)
	case layout.Struct:
		fmt.Fprintf(w, "%sinner%s, err := (&%s).MarshalZAP()\n%sif err != nil {\n%s\treturn nil, err\n%s}\n",
			indent, f.Name, ref, indent, indent, indent)
		fmt.Fprintf(w, "%sob.SetBytes(%s, inner%s)\n", indent, off, f.Name)
	default:
		fmt.Fprintf(w, "%sob.%s(%s, %s(%s))\n", indent, setter[f.Kind], off, goKind[f.Kind], ref)
	}
	if f.Ptr {
		fmt.Fprintf(w, "\t}\n")
	}
}

func emitGet(w *bytes.Buffer, lo string, f layout.Field) error {
	off := lo + f.Name + "Off"
	spell := types.TypeString(f.Type, func(p *types.Package) string { return "" })
	switch f.Kind {
	case layout.Fixed:
		fmt.Fprintf(w, "\tcopy(x.%s[:], o.BytesFixed(%s, %d))\n", f.Name, off, f.N)
		return nil
	case layout.Struct:
		fmt.Fprintf(w, "\tif raw := o.Bytes(%s); len(raw) > 0 {\n", off)
		if f.Ptr {
			fmt.Fprintf(w, "\t\tvar v %s\n\t\tif err := v.UnmarshalZAP(raw); err != nil {\n\t\t\treturn err\n\t\t}\n\t\tx.%s = &v\n",
				spell, f.Name)
		} else {
			fmt.Fprintf(w, "\t\tif err := x.%s.UnmarshalZAP(raw); err != nil {\n\t\t\treturn err\n\t\t}\n", f.Name)
		}
		fmt.Fprintf(w, "\t}\n")
		return nil
	case layout.List:
		return emitListRead(w, lo, f)
	}
	read := fmt.Sprintf("%s(o.%s(%s))", spell, getter[f.Kind], off)
	switch f.Kind {
	case layout.Bytes:
		read = fmt.Sprintf("%s(append([]byte(nil), o.Bytes(%s)...))", spell, off)
	case layout.Text:
		// ZAP decodes a string zero-copy — an unsafe.String over the frame — so a
		// decoded string is a VIEW of a buffer the next call on that connection
		// reuses, and a reply that outlives its call mutates under its owner.
		// The codec clones here, which is what lets client.Call stop walking every
		// reply by reflection to do it (see detach).
		read = fmt.Sprintf("%s(strings.Clone(o.Text(%s)))", spell, off)
	}
	if f.Ptr {
		fmt.Fprintf(w, "\tif v := %s; v != %s {\n\t\tx.%s = &v\n\t}\n", read, zero(f, spell), f.Name)
		return nil
	}
	fmt.Fprintf(w, "\tx.%s = %s\n", f.Name, read)
	return nil
}

// zero is what an absent pointer field reads back as. It mirrors the reflective
// decoder, which allocates only once something is actually there — so a pointer
// to a zero value comes back nil rather than as a pointer to nothing.
func zero(f layout.Field, spell string) string {
	switch f.Kind {
	case layout.Text:
		return `""`
	case layout.Bool:
		return "false"
	}
	return spell + "(0)"
}

func emitListWrite(w *bytes.Buffer, lo string, f layout.Field) error {
	v := lower(f.Name)
	e := *f.Elem
	fmt.Fprintf(w, "\t%sOff, %sN := 0, len(x.%s)\n", v, v, f.Name)
	fmt.Fprintf(w, "\tif %sN > 0 {\n\t\tvar blob []byte\n\t\tfor i := range x.%s {\n", v, f.Name)
	switch e.Kind {
	case layout.Struct:
		fmt.Fprintf(w, "\t\t\tenc, err := x.%s[i].MarshalZAP()\n\t\t\tif err != nil {\n\t\t\t\treturn nil, err\n\t\t\t}\n", f.Name)
	case layout.Text:
		fmt.Fprintf(w, "\t\t\tenc := []byte(x.%s[i])\n", f.Name)
	case layout.Bytes:
		fmt.Fprintf(w, "\t\t\tenc := []byte(x.%s[i])\n", f.Name)
	case layout.Bool:
		fmt.Fprintf(w, "\t\t\tenc := []byte{0}\n\t\t\tif x.%s[i] {\n\t\t\t\tenc[0] = 1\n\t\t\t}\n", f.Name)
	case layout.Fixed:
		fmt.Fprintf(w, "\t\t\tenc := x.%s[i][:]\n", f.Name)
	default:
		width := e.Width()
		fmt.Fprintf(w, "\t\t\tvar wide [8]byte\n")
		fmt.Fprintf(w, "\t\t\tbinary.LittleEndian.PutUint64(wide[:], uint64(%s))\n", listScalar(e, f.Name))
		fmt.Fprintf(w, "\t\t\tenc := append([]byte(nil), wide[:%d]...)\n", width)
	}
	fmt.Fprintf(w, "\t\t\tvar n [4]byte\n\t\t\tbinary.LittleEndian.PutUint32(n[:], uint32(len(enc)))\n")
	fmt.Fprintf(w, "\t\t\tblob = append(blob, n[:]...)\n\t\t\tblob = append(blob, enc...)\n\t\t}\n")
	fmt.Fprintf(w, "\t\t%sOff = b.WriteBytes(blob)\n\t}\n", v)
	return nil
}

// listScalar spells one element for the little-endian write. A float crosses as
// its bits, which is what the reflective encoder does, so the two agree.
func listScalar(e layout.Field, field string) string {
	switch e.Kind {
	case layout.Float32:
		return fmt.Sprintf("math.Float32bits(float32(x.%s[i]))", field)
	case layout.Float64:
		return fmt.Sprintf("math.Float64bits(float64(x.%s[i]))", field)
	}
	return fmt.Sprintf("uint64(x.%s[i])", field)
}

func emitListRead(w *bytes.Buffer, lo string, f layout.Field) error {
	off := lo + f.Name + "Off"
	e := *f.Elem
	spell := types.TypeString(f.Type, func(p *types.Package) string { return "" })
	elem := types.TypeString(e.Type, func(p *types.Package) string { return "" })

	fmt.Fprintf(w, "\tif l := o.List(%s); l.Len() > 0 {\n", off)
	fmt.Fprintf(w, "\t\trows := make(%s, l.Len())\n\t\tfor i := range rows {\n", spell)
	switch e.Kind {
	case layout.Struct:
		fmt.Fprintf(w, "\t\t\tif err := rows[i].UnmarshalZAP(l.BytesAt(i)); err != nil {\n\t\t\t\treturn err\n\t\t\t}\n")
	case layout.Text:
		fmt.Fprintf(w, "\t\t\trows[i] = %s(string(l.BytesAt(i)))\n", elem)
	case layout.Bytes:
		fmt.Fprintf(w, "\t\t\trows[i] = %s(append([]byte(nil), l.BytesAt(i)...))\n", elem)
	case layout.Bool:
		fmt.Fprintf(w, "\t\t\traw := l.BytesAt(i)\n\t\t\trows[i] = %s(len(raw) > 0 && raw[0] != 0)\n", elem)
	case layout.Fixed:
		fmt.Fprintf(w, "\t\t\tcopy(rows[i][:], l.BytesAt(i))\n")
	default:
		fmt.Fprintf(w, "\t\t\trows[i] = %s(%s)\n", elem, listScalarRead(e))
	}
	fmt.Fprintf(w, "\t\t}\n\t\tx.%s = rows\n\t}\n", f.Name)
	return nil
}

func listScalarRead(e layout.Field) string {
	w := e.Width()
	switch e.Kind {
	case layout.Int8, layout.Int16, layout.Int32, layout.Int64:
		// Sign-extend from the element's own width, which is what the reflective
		// decoder does: a negative int32 read as a uint64 is a very large number.
		return fmt.Sprintf("int64(planeWide(l.BytesAt(i))<<%d) >> %d", 64-8*w, 64-8*w)
	case layout.Float32:
		return "math.Float32frombits(uint32(planeWide(l.BytesAt(i))))"
	case layout.Float64:
		return "math.Float64frombits(planeWide(l.BytesAt(i)))"
	}
	return "planeWide(l.BytesAt(i))"
}
